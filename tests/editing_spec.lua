test("cmd: :w writes the file, :q refuses when dirty, :q! doesn't", function()
  local ed = run("abc", "ix<Esc>")
  local path = ed.buf.path
  ed:type(":w<CR>")
  eq(h.read(path), "xabc\n")
  H.ok(not ed.buf:is_dirty())
  ed:type("ay<Esc>:q<CR>")
  H.ok(ed.message:match("E37"), tostring(ed.message))
  H.ok(not ed.closed)
  ed:type(":q!<CR>")
  H.ok(ed.closed)
end)

test("cmd: :wq, :e (new file, existing file, dirty guard), :w name", function()
  local ed = run("abc", "ix<Esc>:wq<CR>")
  eq(h.read(ed.buf.path), "xabc\n"); H.ok(ed.closed)
  ed = h.ed("one")
  h.write(require("recursive_vim.instances").root_dir .. "/other.txt", "second\nfile\n")
  ed:type(":e other.txt<CR>")
  eq(h.lines(ed), { "second", "file" })
  ed:type("ix<Esc>:e third.txt<CR>")
  H.ok(ed.message:match("E37"), tostring(ed.message))
  eq(h.lines(ed), { "xsecond", "file" })
  ed:type(":w<CR>:e t.txt<CR>")
  eq(h.lines(ed), { "one" })
  ed:type(":e brand_new.txt<CR>iNEW<Esc>:w<CR>")
  eq(h.read(ed.buf.path), "NEW\n")
  ed:type(":w copy.txt<CR>")
  eq(h.read(require("recursive_vim.instances").root_dir .. "/copy.txt"), "NEW\n")
end)

test("cmd: :set number / nonumber / tabstop= / number? and unknown command", function()
  local ed = h.ed("x")
  ed:type(":set number<CR>")
  eq(ed.opts.number, true)
  eq(vim.api.nvim_get_option_value("number", { win = ed.win }), true)
  ed:type(":set nonumber<CR>"); eq(ed.opts.number, false)
  ed:type(":set tabstop=3<CR>"); eq(ed.opts.tabstop, 3)
  eq(vim.api.nvim_get_option_value("tabstop", { buf = ed.buf.bufnr }), 3)
  ed:type(":set number?<CR>"); eq(ed.message, "number=false")
  ed:type(":bogus<CR>"); H.ok(ed.message:match("E492"))
  ed:type(":set bogus<CR>"); H.ok(ed.message:match("E518"))
end)

