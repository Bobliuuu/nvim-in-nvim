test("edit: undo / redo (one insert session = one undo step)", function()
  local ed = run("abc", "ix<Esc>ly<Esc>")
  local before = h.lines(ed)
  ed = run("abc", "ihello<Esc>")
  eq(h.lines(ed), { "helloabc" })
  ed:type("u"); eq(h.lines(ed), { "abc" })
  ed:type("<C-r>"); eq(h.lines(ed), { "helloabc" })
  ed:type("dd"); eq(h.lines(ed), { "" })
  ed:type("u"); eq(h.lines(ed), { "helloabc" })
  ed:type("2u"); eq(h.lines(ed), { "abc" })
  ed:type("u"); ok = ed.message; H.ok(ed.message:match("oldest"), "message: " .. tostring(ed.message))
end)

