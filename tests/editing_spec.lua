-- ---------------------------------------------------------------- unit: pure modules
local function mv(lines, key, r, c, n, has, o)
  local ctx = Motions.ctx_from_lines(lines)
  local a, b = Motions.defs[key].fn(ctx, r, c, n or 1, has or false, o or {})
  return { a, b }
end

test("unit/motions: w b e across words, punctuation and lines", function()
  local L = { "foo bar.baz", "  qux" }
  eq(mv(L, "w", 0, 0), { 0, 4 })
  eq(mv(L, "w", 0, 4), { 0, 7 })
  eq(mv(L, "w", 0, 7), { 0, 8 })
  eq(mv(L, "w", 0, 8), { 1, 2 })
  eq(mv(L, "w", 0, 0, 3), { 0, 8 })
  eq(mv(L, "b", 1, 2), { 0, 8 })
  eq(mv(L, "b", 0, 8), { 0, 7 })
  eq(mv(L, "e", 0, 0), { 0, 2 })
  eq(mv(L, "e", 0, 2), { 0, 6 })
end)

test("unit/motions: 0 ^ $ gg G and counts", function()
  local L = { "  hi there", "x", "" }
  eq(mv(L, "0", 0, 5), { 0, 0 })
  eq(mv(L, "^", 0, 5), { 0, 2 })
  eq(mv(L, "$", 0, 0)[2], 9)
  eq(mv(L, "G", 0, 0), { 2, 0 })
  eq(mv(L, "G", 2, 0, 2, true), { 1, 0 })
  eq(mv(L, "gg", 2, 0), { 0, 2 })
end)

test("unit/motions: j/k remember the wanted column", function()
  local L = { "abcdef", "ab", "abcdef" }
  local ctx = Motions.ctx_from_lines(L)
  local r, c, keep = Motions.defs.j.fn(ctx, 0, 4, 1, false, {})
  eq({ r, c, keep }, { 1, 1, true })
  ctx.want = 4
  local r2, c2 = Motions.defs.j.fn(ctx, 1, 1, 1, false, {})
  eq({ r2, c2 }, { 2, 4 })
end)

test("unit/motions: utf-8 aware", function()
  local L = { "日本語 テスト" }
  eq(mv(L, "l", 0, 0), { 0, 3 })
  eq(mv(L, "w", 0, 0), { 0, 10 })
  eq(T.last("é"), 0)
  eq(T.next("éa", 0), 2)
end)

test("unit/motions: search finds, wraps, goes backwards", function()
  local ctx = Motions.ctx_from_lines({ "foo", "bar foo", "baz" })
  local r, c = Motions.find(ctx, 0, 0, "foo", 1); eq({ r, c }, { 1, 4 })
  r, c = Motions.find(ctx, 1, 4, "foo", 1); eq({ r, c }, { 0, 0 })
  r, c = Motions.find(ctx, 0, 0, "foo", -1); eq({ r, c }, { 1, 4 })
end)

test("unit/keys: parse and normalize", function()
  eq(Keys.parse("<leader>n", " "), { " ", "n" })
  eq(Keys.parse("<C-R>x"), { "<C-r>", "x" })
  eq(Keys.parse("gg<CR>"), { "g", "g", "<CR>" })
  eq(Keys.parse("é<lt>"), { "é", "<" })
  eq(Keys.normalize("\27"), "<Esc>")
  eq(Keys.normalize(" "), " ")
  eq(Keys.normalize("\18"), "<C-r>")
  eq(Keys.from_text("a\tb\n"), { "a", "<Tab>", "b", "<CR>" })
end)

test("unit/registers", function()
  local r = Registers.new()
  r:set(nil, { "a" }, false, "yank")
  r:set("b", { "b" }, true, "delete")
  eq(r:get().lines, { "b" })
  eq(r:get("0").lines, { "a" })
  eq(r:get("b").linewise, true)
  r:set("_", { "gone" }, false)
  eq(r:get().lines, { "b" })
end)

-- ---------------------------------------------------------------- integration: real buffers/windows
local function run(text, keys, at)
  local ed = h.ed(text, at)
  ed:type(keys)
  return ed
end

test("edit: modes and insertion (i a I A o O)", function()
  eq(h.lines(run("abc", "ix<Esc>")), { "xabc" })
  eq(h.lines(run("abc", "ax<Esc>")), { "axbc" })
  eq(h.lines(run("  abc", "Ix<Esc>")), { "  xabc" })
  eq(h.lines(run("abc", "Ax<Esc>")), { "abcx" })
  eq(h.lines(run("abc\ndef", "oX<Esc>")), { "abc", "X", "def" })
  eq(h.lines(run("abc\ndef", "jOX<Esc>")), { "abc", "X", "def" })
  local ed = run("abc", "i")
  eq(ed.mode, "i")
  ed:type("<Esc>")
  eq(ed.mode, "n")
end)

test("edit: insert Enter, Backspace (joins lines), Tab, unicode", function()
  eq(h.lines(run("ab", "a<CR>X<Esc>")), { "a", "Xb" })
  eq(h.lines(run("ab\ncd", "ji<BS><Esc>")), { "abcd" })
  eq(h.lines(run("é", "A→<BS><Esc>")), { "é" })
  eq(h.lines(run("x", "i<Tab><Esc>")), { "\tx" })
  local ed = h.ed("x"); ed.cfg.vim.opt.expandtab = true; ed.cfg.vim.opt.tabstop = 2
  ed:type("i<Tab><Esc>"); eq(h.lines(ed), { "  x" })
  eq(h.lines(run("", "i日本😀<Esc>")), { "日本😀" })
end)

test("edit: x dd dw cw yy p P", function()
  eq(h.lines(run("abc", "x")), { "bc" })
  eq(h.lines(run("a\nb\nc", "jdd")), { "a", "c" })
  eq(h.lines(run("one two three", "dw")), { "two three" })
  eq(h.lines(run("one two three", "wcwXX<Esc>")), { "one XX three" })
  eq(h.lines(run("a\nb", "yyp")), { "a", "a", "b" })
  eq(h.lines(run("a\nb", "yyjP")), { "a", "a", "b" })
  eq(h.lines(run("ab", "xp")), { "ba" })
  eq(h.lines(run("only", "dd")), { "" })
end)

test("edit: dw on last word of a line does not join lines", function()
  eq(h.lines(run("foo bar\nbaz", "wdw")), { "foo ", "baz" })
end)

test("edit: composition d+motion, c+motion, y+motion", function()
  eq(h.lines(run("one two three", "d$")), { "" })
  eq(h.lines(run("one two three", "wd0")), { "two three" })
  eq(h.lines(run("a\nb\nc\nd", "dj")), { "c", "d" })
  eq(h.lines(run("a\nb\nc\nd", "jdk")), { "c", "d" })
  eq(h.lines(run("a\nb\nc\nd", "dG")), { "" })
  eq(h.lines(run("a\nb\nc\nd", "Gdgg")), { "" })
  eq(h.lines(run("one two", "de")), { " two" })
  eq(h.lines(run("one two", "wdb")), { "two" })
  eq(h.lines(run("one two", "c$X<Esc>")), { "X" })
  eq(h.lines(run("one two", "ywP")), { "one one two" })
end)

test("edit: counts 5j 3w 2dd d2w 3x", function()
  local ed = run("1\n2\n3\n4\n5\n6\n7", "5j"); eq(ed.row, 5)
  ed = run("a b c d e", "3w"); eq(ed.col, 6)
  eq(h.lines(run("1\n2\n3\n4", "2dd")), { "3", "4" })
  eq(h.lines(run("a b c d", "d2w")), { "c d" })
  eq(h.lines(run("a b c d", "2d2w")), { "" })
  eq(h.lines(run("abcdef", "3x")), { "def" })
  eq(h.lines(run("a\nb\nc", "3dd")), { "" })
  eq(h.lines(run("a\nb\nc\nd\ne", "2yy3jp")), { "a", "b", "c", "d", "a", "b", "e" })
  eq(h.lines(run("x", "3ix<Esc>")), { "xx" })
end)

test("edit: x D C s S Y J r", function()
